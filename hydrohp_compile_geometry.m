function geometry = hydrohp_compile_geometry(cell_sections, face_sections, gravity_m_s2)
%HYDROHP_COMPILE_GEOMETRY Pack mapped section tables into numeric arrays.
%
% The varying-section kernel evaluates the same hydraulic tables at every
% time step. This function validates the mapped sections once and stores
% their breakpoints and piecewise-cubic (pchip) coefficients in padded
% matrices, one row per section. Evaluating these coefficients with the
% same local Horner form used by interp1 reproduces interp1 'pchip' and
% 'linear' results exactly, so the compiled kernel does not change the
% solution. The boundary characteristic integral depends on gravity, so the
% compiled geometry is tied to one gravity value.

if nargin < 3
    gravity_m_s2 = 9.81;
end
if numel(face_sections) ~= numel(cell_sections) + 1
    error('hydrohp:GridSizeMismatch', ...
        'The grid requires N cell sections and N+1 face sections.');
end
geometry = struct( ...
    'cell_count', numel(cell_sections), ...
    'gravity_m_s2', gravity_m_s2, ...
    'cells', compile_set(cell_sections(:)), ...
    'faces', compile_set(face_sections(:)), ...
    'upstream_face', boundary_section(face_sections(1), gravity_m_s2), ...
    'downstream_face', boundary_section(face_sections(end), gravity_m_s2));
end

function set = compile_set(sections)
count = numel(sections);
rows = zeros(count, 1);
for index = 1:count
    validate_section(sections(index));
    rows(index) = height(sections(index).table);
end
if any(rows < 2)
    error('hydrohp:InvalidSectionTable', ...
        'Each local section table needs at least two rows.');
end
width = max(rows);
stage = inf(count, width);
area = inf(count, width);
top_width = zeros(count, width);
area_of_stage = zeros(count, width - 1, 4);
hydrostatic_of_stage = zeros(count, width - 1, 4);
conveyance_of_stage = zeros(count, width - 1, 4);
depth_of_area = zeros(count, width - 1, 4);
resolution = zeros(count, 1);
for index = 1:count
    data = sections(index).table;
    n = rows(index);
    stage(index, 1:n) = data.water_surface_elevation_m;
    area(index, 1:n) = data.area_m2;
    top_width(index, 1:n) = data.top_width_m;
    area_of_stage(index, 1:n-1, :) = pchip_coefficients( ...
        data.water_surface_elevation_m, data.area_m2);
    hydrostatic_of_stage(index, 1:n-1, :) = pchip_coefficients( ...
        data.water_surface_elevation_m, data.hydrostatic_integral_m3);
    conveyance_of_stage(index, 1:n-1, :) = pchip_coefficients( ...
        data.water_surface_elevation_m, data.conveyance_m3s);
    depth_of_area(index, 1:n-1, :) = pchip_coefficients( ...
        data.area_m2, data.depth_m);
    resolution(index) = max(diff(data.depth_m));
end
set = struct( ...
    'count', count, ...
    'rows', rows, ...
    'x_m', [sections.x_m].', ...
    'invert_elevation_m', [sections.invert_elevation_m].', ...
    'maximum_water_surface_elevation_m', ...
        [sections.maximum_water_surface_elevation_m].', ...
    'maximum_area_m2', area(sub2ind([count, width], (1:count).', rows)), ...
    'table_resolution_m', resolution, ...
    'stage_m', stage, ...
    'area_m2', area, ...
    'top_width_m', top_width, ...
    'area_of_stage', area_of_stage, ...
    'hydrostatic_of_stage', hydrostatic_of_stage, ...
    'conveyance_of_stage', conveyance_of_stage, ...
    'depth_of_area', depth_of_area);
end

function coefficients = pchip_coefficients(x, y)
pp = pchip(x(:).', y(:).');
coefficients = reshape(pp.coefs, 1, [], 4);
end

function section = boundary_section(source, g)
% Boundary faces keep their numeric table for the scalar boundary solvers,
% a one-row compiled set for state evaluation, and the pchip curves of the
% characteristic integral phi(A) and of conveyance against area.
validate_section(source);
data = source.table;
table_struct = struct( ...
    'depth_m', data.depth_m, ...
    'water_surface_elevation_m', data.water_surface_elevation_m, ...
    'area_m2', data.area_m2, ...
    'top_width_m', data.top_width_m, ...
    'hydrostatic_integral_m3', data.hydrostatic_integral_m3, ...
    'conveyance_m3s', data.conveyance_m3s);
wet = data.area_m2 > 0 & data.top_width_m > 0;
depth = data.depth_m(wet);
table_area = data.area_m2(wet);
integrand = sqrt(g * data.top_width_m(wet) ./ table_area);
table_phi = zeros(size(table_area));
table_phi(1) = 2 * depth(1) * integrand(1);
if numel(depth) > 1
    integrated = cumtrapz(depth, integrand);
    table_phi(2:end) = table_phi(1) + integrated(2:end);
end
section = struct( ...
    'x_m', source.x_m, ...
    'invert_elevation_m', source.invert_elevation_m, ...
    'maximum_water_surface_elevation_m', ...
        source.maximum_water_surface_elevation_m, ...
    'table_resolution_m', max(diff(data.depth_m)), ...
    'table', table_struct, ...
    'set', compile_set(source), ...
    'phi_of_area', curve(table_area, table_phi), ...
    'conveyance_of_area', curve(data.area_m2, data.conveyance_m3s));
end

function result = curve(x, y)
pp = pchip(x(:).', y(:).');
result = struct('breaks', x(:).', 'coefficients', pp.coefs);
end

function validate_section(section)
required = {'x_m', 'invert_elevation_m', ...
    'maximum_water_surface_elevation_m', 'table'};
table_fields = {'depth_m', 'water_surface_elevation_m', 'area_m2', ...
    'top_width_m', 'hydrostatic_integral_m3', 'conveyance_m3s'};
if ~isscalar(section) || ~all(isfield(section, required)) || ...
        ~istable(section.table) || ...
        ~all(ismember(table_fields, section.table.Properties.VariableNames))
    error('hydrohp:InvalidSectionTable', ...
        'Each local section must contain an H4/H5a hydraulic table.');
end
end
