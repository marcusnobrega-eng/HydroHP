function result = hydrohp_run_varying(input)
%HYDROHP_RUN_VARYING Run the tested varying-section finite-volume kernel.

required = {'section_data', 'face_x_m', 'hydrograph_time_s', ...
    'hydrograph_discharge_m3s', 'duration_s', 'downstream'};
if ~isstruct(input) || ~isscalar(input) || ~all(isfield(input, required))
    error('hydrohp:InvalidVaryingInput', ...
        'Input must define sections, grid, hydrograph, duration, and downstream boundary.');
end
input = apply_defaults(input);
validate_input(input);
initialize_diagnostics(input);

face_x_m = input.face_x_m(:);
dx_m = diff(face_x_m);
if max(abs(dx_m - dx_m(1))) > 1e-10 * max(1, dx_m(1))
    error('hydrohp:NonuniformGrid', 'The H6 runner currently requires a uniform grid.');
end
dx_m = dx_m(1);
cell_x_m = face_x_m(1:end-1) + dx_m / 2;
cell_sections = hydrohp_map_sections_to_grid(input.section_data, cell_x_m);
face_sections = hydrohp_map_sections_to_grid(input.section_data, face_x_m);
geometry = hydrohp_compile_geometry( ...
    cell_sections, face_sections, input.gravity_m_s2);
step = make_step_function(cell_sections, face_sections, geometry, input);

[area_m2, discharge_m3s] = initial_state( ...
    cell_sections, face_sections, input);
initialization = struct('type', input.initialization_type, ...
    'base_discharge_m3s', input.base_discharge_m3s, ...
    'spinup_duration_s', input.spinup_duration_s, ...
    'converged', true, 'relative_discharge_error', 0, ...
    'relative_state_change_rate_per_s', 0, 'ledger', struct(), ...
    'final_area_m2', area_m2, 'final_discharge_m3s', discharge_m3s);

status = "completed";
overtopping = struct([]);
if input.spinup_duration_s > 0
    [area_m2, discharge_m3s, ~, initialization.ledger, ...
        initialization.relative_state_change_rate_per_s, overtopping] = integrate( ...
        area_m2, discharge_m3s, input.spinup_duration_s, ...
        @(time) input.base_discharge_m3s, struct('record', false), step, ...
        dx_m, input, "spinup");
    initialization.relative_discharge_error = max(abs( ...
        discharge_m3s - input.base_discharge_m3s)) / ...
        max(1, abs(input.base_discharge_m3s));
    initialization.final_area_m2 = area_m2;
    initialization.final_discharge_m3s = discharge_m3s;
    initialization.converged = ...
        initialization.relative_state_change_rate_per_s <= ...
        input.steady_tolerance_per_s;
    if ~initialization.converged && isempty(overtopping)
        error('hydrohp:SteadyInitializationFailed', ...
            'Spin-up state still changes at %.6g per second.', ...
            initialization.relative_state_change_rate_per_s);
    end
end

forcing = @(time) interp1(input.hydrograph_time_s, ...
    input.hydrograph_discharge_m3s, time, 'linear');
outputs = output_plan(input, geometry, cell_x_m, face_x_m);
if isempty(overtopping)
    [area_m2, discharge_m3s, history, ledger, ~, overtopping] = integrate( ...
        area_m2, discharge_m3s, input.duration_s, forcing, outputs, ...
        step, dx_m, input, "event");
else
    history = struct('time_s', zeros(0, 1), ...
        'area_m2', zeros(0, numel(cell_x_m)), ...
        'discharge_m3s', zeros(0, numel(cell_x_m)), ...
        'maxima', struct(), 'probes', struct());
    ledger = struct();
end
if ~isempty(overtopping)
    status = "overtopped";
end

result = struct( ...
    'status', status, ...
    'overtopping', overtopping, ...
    'time_s', history.time_s, ...
    'x_m', cell_x_m, ...
    'area_m2', history.area_m2, ...
    'discharge_m3s', history.discharge_m3s, ...
    'final_area_m2', area_m2, ...
    'final_discharge_m3s', discharge_m3s, ...
    'maxima', history.maxima, ...
    'probes', history.probes, ...
    'ledger', ledger, ...
    'initialization', initialization, ...
    'metadata', struct('solver', "varying-section-hll", ...
        'kernel', input.kernel, ...
        'reconstruction', input.reconstruction, ...
        'output_interval_s', input.output_interval_s, ...
        'overtopping_action', input.overtopping_action, ...
        'boundary_formulation', input.boundary_formulation, ...
        'cfl_target', input.cfl_target, ...
        'minimum_dt_s', input.minimum_dt_s, ...
        'maximum_dt_s', input.maximum_dt_s, ...
        'downstream', input.downstream, ...
        'include_friction', input.include_friction));
end

function input = apply_defaults(input)
defaults = struct( ...
    'gravity_m_s2', 9.81, ...
    'cfl_target', 0.7, ...
    'minimum_area_m2', 1e-10, ...
    'minimum_dt_s', 1e-5, ...
    'maximum_dt_s', 1, ...
    'include_friction', true, ...
    'base_discharge_m3s', input.hydrograph_discharge_m3s(1), ...
    'initialization_type', "normal_depth", ...
    'initial_stage_m', NaN, ...
    'spinup_duration_s', 0, ...
    'steady_tolerance_per_s', 1e-4, ...
    'progress_file', "", ...
    'checkpoint_file', "", ...
    'diagnostic_wall_interval_s', 300, ...
    'kernel', "compiled", ...
    'negative_area_capture_file', "", ...
    'negative_area_tolerance_m2', NaN, ...
    'reconstruction', "hydrostatic", ...
    'output_interval_s', 0, ...
    'probe_x_m', zeros(0, 1), ...
    'overtopping_action', "error", ...
    'boundary_formulation', "regime");
names = fieldnames(defaults);
for index = 1:numel(names)
    if ~isfield(input, names{index})
        input.(names{index}) = defaults.(names{index});
    end
end
input.progress_file = string(input.progress_file);
input.checkpoint_file = string(input.checkpoint_file);
input.kernel = lower(string(input.kernel));
input.negative_area_capture_file = string(input.negative_area_capture_file);
input.reconstruction = lower(string(input.reconstruction));
input.overtopping_action = lower(string(input.overtopping_action));
input.boundary_formulation = lower(string(input.boundary_formulation));
if isnan(input.negative_area_tolerance_m2)
    input.negative_area_tolerance_m2 = input.minimum_area_m2;
end
end

function validate_input(input)
time = input.hydrograph_time_s(:);
discharge = input.hydrograph_discharge_m3s(:);
if numel(time) ~= numel(discharge) || numel(time) < 2 || ...
        any(~isfinite([time; discharge])) || any(diff(time) <= 0) || ...
        time(1) ~= 0 || input.duration_s <= 0 || time(end) < input.duration_s
    error('hydrohp:InvalidHydrograph', ...
        'Hydrograph arrays must be finite, increasing, start at zero, and cover duration_s.');
end
if any(discharge < 0)
    error('hydrohp:InvalidHydrograph', 'Negative upstream discharge is not supported.');
end
if ~isnumeric(input.face_x_m) || numel(input.face_x_m) < 3 || ...
        any(~isfinite(input.face_x_m)) || any(diff(input.face_x_m) <= 0)
    error('hydrohp:InvalidGrid', 'face_x_m must be finite and strictly increasing.');
end
positive_scalars = {'duration_s', 'gravity_m_s2', 'cfl_target', ...
    'minimum_dt_s', 'maximum_dt_s', 'steady_tolerance_per_s', ...
    'diagnostic_wall_interval_s'};
for index = 1:numel(positive_scalars)
    value = input.(positive_scalars{index});
    if ~isscalar(value) || ~isfinite(value) || value <= 0
        error('hydrohp:InvalidVaryingInput', ...
            '%s must be a positive finite scalar.', positive_scalars{index});
    end
end
if input.cfl_target > 1 || input.minimum_dt_s > input.maximum_dt_s || ...
        input.spinup_duration_s < 0 || input.minimum_area_m2 < 0
    error('hydrohp:InvalidVaryingInput', 'CFL, time-step, spin-up, or area limits are invalid.');
end
if ~isscalar(input.kernel) || ~ismember(input.kernel, ["compiled", "reference"])
    error('hydrohp:InvalidVaryingInput', ...
        'kernel must be "compiled" or "reference".');
end
if ~isscalar(input.reconstruction) || ...
        ~ismember(input.reconstruction, ["stage", "hydrostatic"]) || ...
        (input.reconstruction == "hydrostatic" && input.kernel ~= "compiled")
    error('hydrohp:InvalidVaryingInput', ...
        ['reconstruction must be "stage" or "hydrostatic"; ' ...
        '"hydrostatic" needs the compiled kernel.']);
end
if ~isscalar(input.output_interval_s) || ...
        ~isfinite(input.output_interval_s) || input.output_interval_s < 0
    error('hydrohp:InvalidVaryingInput', ...
        'output_interval_s must be a finite nonnegative scalar (0 stores every step).');
end
probe_x_m = input.probe_x_m(:);
if ~isnumeric(probe_x_m) || any(~isfinite(probe_x_m)) || ...
        any(probe_x_m < input.face_x_m(1)) || any(probe_x_m > input.face_x_m(end))
    error('hydrohp:InvalidVaryingInput', ...
        'probe_x_m must hold finite locations inside the grid.');
end
if ~isscalar(input.boundary_formulation) || ...
        ~ismember(input.boundary_formulation, ["legacy", "regime"]) || ...
        (input.boundary_formulation == "regime" && input.kernel ~= "compiled")
    error('hydrohp:InvalidVaryingInput', ...
        ['boundary_formulation must be "legacy" or "regime"; ' ...
        '"regime" needs the compiled kernel.']);
end
if ~isscalar(input.overtopping_action) || ...
        ~ismember(input.overtopping_action, ["error", "stop"])
    error('hydrohp:InvalidVaryingInput', ...
        'overtopping_action must be "error" or "stop".');
end
capture = input.negative_area_capture_file;
if ~isscalar(capture) || (strlength(capture) > 0 && ...
        (input.kernel ~= "compiled" || ~isfolder(fileparts(capture))))
    error('hydrohp:InvalidVaryingInput', ...
        ['negative_area_capture_file needs the compiled kernel and a ' ...
        'file in an existing directory.']);
end
if ~isscalar(input.negative_area_tolerance_m2) || ...
        ~isfinite(input.negative_area_tolerance_m2) || ...
        input.negative_area_tolerance_m2 < 0
    error('hydrohp:InvalidVaryingInput', ...
        'negative_area_tolerance_m2 must be a finite nonnegative scalar.');
end
downstream_type = lower(string(input.downstream.type));
if ~isscalar(downstream_type) || ...
        ~ismember(downstream_type, ["normal_depth", "stage"])
    error('hydrohp:InvalidDownstreamType', ...
        'Downstream type must be "normal_depth" or "stage".');
end
if downstream_type == "normal_depth" && ...
        (~isfield(input.downstream, 'slope') || ...
        ~isscalar(input.downstream.slope) || ...
        ~isfinite(input.downstream.slope) || input.downstream.slope <= 0)
    error('hydrohp:InvalidDownstreamSlope', ...
        'A normal-depth boundary requires a positive finite slope.');
elseif downstream_type == "stage" && ...
        (~isfield(input.downstream, 'stage_m') || ...
        ~isscalar(input.downstream.stage_m) || ~isfinite(input.downstream.stage_m))
    error('hydrohp:InvalidDownstreamStage', ...
        'A stage boundary requires one finite stage_m value.');
end
for field_name = ["progress_file", "checkpoint_file"]
    value = input.(field_name);
    if ~isscalar(value) || (strlength(value) > 0 && ~isfolder(fileparts(value)))
        error('hydrohp:InvalidDiagnosticPath', ...
            '%s must be empty or name a file in an existing directory.', field_name);
    end
end
end

function initialize_diagnostics(input)
if strlength(input.progress_file) == 0
    return
end
file_id = fopen(input.progress_file, 'w');
if file_id < 0
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not create progress file %s.', input.progress_file);
end
cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, ['phase\tmodel_time_s\tduration_s\tprogress_fraction\t' ...
    'step_count\taccepted_dt_s\tmaximum_cfl_number\tstorage_m3\t' ...
    'cumulative_inflow_m3\tcumulative_outflow_m3\t' ...
    'wet_dry_adjustment_m3\twall_elapsed_s\n']);
end

function [area, discharge] = initial_state(sections, face_sections, input)
cell_count = numel(sections);
discharge = input.base_discharge_m3s * ones(cell_count, 1);
initialization_type = lower(string(input.initialization_type));
if initialization_type == "normal_depth"
    if lower(string(input.downstream.type)) ~= "normal_depth" || ...
            ~isfield(input.downstream, 'slope') || input.downstream.slope <= 0
        error('hydrohp:InvalidInitialization', ...
            'Normal-depth initialization requires a positive downstream slope.');
    end
    local_slope = ([face_sections(1:end-1).invert_elevation_m].' - ...
        [face_sections(2:end).invert_elevation_m].') ./ diff(input.face_x_m(:));
    if any(local_slope <= 0)
        error('hydrohp:InvalidInitialization', ...
            'Normal-depth initialization requires a positive local bed slope in every cell.');
    end
    target_conveyance = input.base_discharge_m3s ./ sqrt(local_slope);
    area = zeros(cell_count, 1);
    for index = 1:cell_count
        table_data = sections(index).table;
        if target_conveyance(index) > table_data.conveyance_m3s(end)
            error('hydrohp:InitializationOutsideSectionRange', ...
                'Base flow exceeds the conveyance range at x = %.6g m.', sections(index).x_m);
        end
        area(index) = interp1(table_data.conveyance_m3s, ...
            table_data.area_m2, target_conveyance(index), 'pchip');
    end
elseif initialization_type == "stage"
    stage = input.initial_stage_m;
    if isscalar(stage)
        stage = repmat(stage, cell_count, 1);
    end
    if ~isnumeric(stage) || numel(stage) ~= cell_count || any(~isfinite(stage))
        error('hydrohp:InvalidInitialization', ...
            'initial_stage_m must be a finite scalar or one value per cell.');
    end
    area = zeros(cell_count, 1);
    for index = 1:cell_count
        if stage(index) > sections(index).maximum_water_surface_elevation_m
            error('hydrohp:InitializationOutsideSectionRange', ...
                'Initial stage exceeds the section range at x = %.6g m.', ...
                sections(index).x_m);
        elseif stage(index) > sections(index).invert_elevation_m
            area(index) = interp1( ...
                sections(index).table.water_surface_elevation_m, ...
                sections(index).table.area_m2, stage(index), 'pchip');
        end
    end
else
    error('hydrohp:InvalidInitialization', ...
        'initialization_type must be "normal_depth" or "stage".');
end
end

function [area, discharge, history, ledger, final_change_rate_per_s, ...
        overtopping] = integrate( ...
        area, discharge, duration_s, forcing, outputs, ...
        step, dx_m, input, phase)
time_s = 0;
wall_timer = tic;
last_diagnostic_wall_s = -inf;
candidate_dt_s = input.maximum_dt_s;
initial_storage_m3 = sum(area) * dx_m;
cumulative_inflow_m3 = 0;
cumulative_outflow_m3 = 0;
cumulative_adjustment_m3 = 0;
final_change_rate_per_s = inf;
step_count = 0;
minimum_accepted_dt_s = inf;
maximum_cfl_number = 0;
stage_endpoint_clamp_count = 0;
maximum_stage_endpoint_excess_m = 0;
record = outputs.record;
if record
    % Event outputs (P3): sparse state history at output_interval_s (every
    % step when 0), online maxima, and per-step probe series. Recording never
    % changes the time steps, so the solution equals a full-history run.
    cell_count = numel(area);
    interval_s = outputs.interval_s;
    if interval_s > 0
        history_capacity = floor(duration_s / interval_s) + 2;
    else
        history_capacity = 1024;
    end
    history_time = zeros(history_capacity, 1);
    history_area = zeros(history_capacity, cell_count);
    history_discharge = zeros(history_capacity, cell_count);
    history_count = 1;
    history_area(1, :) = area.';
    history_discharge(1, :) = discharge.';
    next_output_s = interval_s;

    depth = hydrohp_compiled_cell_depth(outputs.cells, area);
    speed = cell_speed(area, discharge, input.minimum_area_m2);
    maximum_depth = depth;
    maximum_area = area;
    maximum_discharge = abs(discharge);
    maximum_speed = speed;
    maximum_depth_speed = depth .* speed;
    time_of_maximum_depth = zeros(cell_count, 1);
    time_of_maximum_speed = zeros(cell_count, 1);
    maximum_face_flux = zeros(cell_count + 1, 1);

    probe_cells = outputs.probe_cells;
    probe_faces = outputs.probe_faces;
    probe_capacity = 1024;
    probe_time = zeros(probe_capacity, 1);
    probe_area = zeros(probe_capacity, numel(probe_cells));
    probe_discharge = zeros(probe_capacity, numel(probe_cells));
    probe_depth = zeros(probe_capacity, numel(probe_cells));
    probe_face_flux = NaN(probe_capacity, numel(probe_faces));
    probe_count = 1;
    probe_area(1, :) = area(probe_cells).';
    probe_discharge(1, :) = discharge(probe_cells).';
    probe_depth(1, :) = depth(probe_cells).';
end

overtopping = struct([]);
upstream_code_counts = zeros(1, 4);    % codes 0..3
downstream_code_counts = zeros(1, 3);  % codes 1..3
while time_s < duration_s
    dt_s = min(candidate_dt_s, duration_s - time_s);
    next_break = input.hydrograph_time_s(find( ...
        input.hydrograph_time_s > time_s, 1, 'first'));
    if ~isempty(next_break)
        dt_s = min(dt_s, next_break - time_s);
    end
    accepted = false;
    while ~accepted
        boundary = make_boundary(input.downstream, ...
            forcing(time_s + dt_s / 2), input.initialization_type);
        try
            [area_new, discharge_new, diagnostic] = step( ...
                area, discharge, dx_m, dt_s, boundary);
            accepted = true;
        catch exception
            if input.overtopping_action == "stop" && ...
                    ismember(exception.identifier, ...
                    {'hydrohp:AreaOutsideSectionRange', ...
                    'hydrohp:StageOutsideSectionRange', ...
                    'hydrohp:BoundaryOutsideSectionRange'})
                overtopping = overtopping_record(phase, time_s, step_count, ...
                    exception);
                break
            end
            if ~strcmp(exception.identifier, 'hydrohp:CFLViolation')
                rethrow(exception)
            end
            dt_s = dt_s / 2;
            if dt_s < input.minimum_dt_s
                error('hydrohp:MinimumTimeStep', ...
                    ['CFL control requires dt below minimum_dt_s at t = %.6g s. ' ...
                    'First-cell area/discharge are %.6g m2 and %.6g m3/s. ' ...
                    'Last diagnostic: %s'], time_s, area(1), discharge(1), ...
                    exception.message);
            end
        end
    end

    if ~isempty(overtopping)
        break
    end
    if strlength(input.negative_area_capture_file) > 0 && ...
            ~isempty(diagnostic.negative_area_event)
        capture_negative_area(input, phase, time_s, dt_s, step_count + 1, ...
            boundary, area, discharge, area_new, discharge_new, dx_m, ...
            initial_storage_m3, cumulative_inflow_m3, ...
            cumulative_outflow_m3, cumulative_adjustment_m3, diagnostic);
    end
    time_s = time_s + dt_s;
    step_count = step_count + 1;
    minimum_accepted_dt_s = min(minimum_accepted_dt_s, dt_s);
    maximum_cfl_number = max(maximum_cfl_number, diagnostic.cfl_number);
    area_change_rate = max(abs(area_new - area) ./ max(abs(area), 1e-6)) / dt_s;
    discharge_change_rate = max(abs(discharge_new - discharge)) / ...
        max(1, max(abs(discharge))) / dt_s;
    final_change_rate_per_s = max(area_change_rate, discharge_change_rate);
    area = area_new;
    discharge = discharge_new;
    cumulative_inflow_m3 = cumulative_inflow_m3 + ...
        diagnostic.boundary_inflow_volume_m3;
    cumulative_outflow_m3 = cumulative_outflow_m3 + ...
        diagnostic.boundary_outflow_volume_m3;
    cumulative_adjustment_m3 = cumulative_adjustment_m3 + ...
        diagnostic.volume_adjustment_m3;
    stage_endpoint_clamp_count = stage_endpoint_clamp_count + ...
        diagnostic.stage_endpoint_clamp_count;
    maximum_stage_endpoint_excess_m = max( ...
        maximum_stage_endpoint_excess_m, ...
        diagnostic.maximum_stage_endpoint_excess_m);
    if isfield(diagnostic, 'upstream_boundary_code')
        if ~isnan(diagnostic.upstream_boundary_code)
            upstream_code_counts(diagnostic.upstream_boundary_code + 1) = ...
                upstream_code_counts(diagnostic.upstream_boundary_code + 1) + 1;
        end
        if ~isnan(diagnostic.downstream_boundary_code)
            downstream_code_counts(diagnostic.downstream_boundary_code) = ...
                downstream_code_counts(diagnostic.downstream_boundary_code) + 1;
        end
    end
    candidate_dt_s = min(input.maximum_dt_s, 0.95 * diagnostic.recommended_dt_s);
    if candidate_dt_s < input.minimum_dt_s
        error('hydrohp:MinimumTimeStep', ...
            'The recommended step fell below minimum_dt_s at t = %.6g s.', time_s);
    end
    if record
        depth = hydrohp_compiled_cell_depth(outputs.cells, area);
        speed = cell_speed(area, discharge, input.minimum_area_m2);
        deeper = depth > maximum_depth;
        maximum_depth(deeper) = depth(deeper);
        time_of_maximum_depth(deeper) = time_s;
        faster = speed > maximum_speed;
        maximum_speed(faster) = speed(faster);
        time_of_maximum_speed(faster) = time_s;
        maximum_area = max(maximum_area, area);
        maximum_discharge = max(maximum_discharge, abs(discharge));
        maximum_depth_speed = max(maximum_depth_speed, depth .* speed);
        if outputs.face_flux
            maximum_face_flux = max(maximum_face_flux, ...
                abs(diagnostic.face_mass_flux_m3s));
        end

        probe_count = probe_count + 1;
        if probe_count > probe_capacity
            probe_time = [probe_time; zeros(size(probe_time))]; %#ok<AGROW>
            probe_area = [probe_area; zeros(size(probe_area))]; %#ok<AGROW>
            probe_discharge = [probe_discharge; zeros(size(probe_discharge))]; %#ok<AGROW>
            probe_depth = [probe_depth; zeros(size(probe_depth))]; %#ok<AGROW>
            probe_face_flux = [probe_face_flux; NaN(size(probe_face_flux))]; %#ok<AGROW>
            probe_capacity = 2 * probe_capacity;
        end
        probe_time(probe_count) = time_s;
        probe_area(probe_count, :) = area(probe_cells).';
        probe_discharge(probe_count, :) = discharge(probe_cells).';
        probe_depth(probe_count, :) = depth(probe_cells).';
        if outputs.face_flux
            probe_face_flux(probe_count, :) = ...
                diagnostic.face_mass_flux_m3s(probe_faces).';
        end

        if interval_s == 0 || time_s >= next_output_s || time_s >= duration_s
            history_count = history_count + 1;
            if history_count > history_capacity
                history_time = [history_time; zeros(size(history_time))]; %#ok<AGROW>
                history_area = [history_area; zeros(size(history_area))]; %#ok<AGROW>
                history_discharge = [history_discharge; ...
                    zeros(size(history_discharge))]; %#ok<AGROW>
                history_capacity = 2 * history_capacity;
            end
            history_time(history_count) = time_s;
            history_area(history_count, :) = area.';
            history_discharge(history_count, :) = discharge.';
            if interval_s > 0
                next_output_s = (floor(time_s / interval_s) + 1) * interval_s;
            end
        end
    end
    wall_elapsed_s = toc(wall_timer);
    if wall_elapsed_s - last_diagnostic_wall_s >= ...
            input.diagnostic_wall_interval_s || time_s >= duration_s
        partial_ledger = make_ledger(area, dx_m, step_count, ...
            minimum_accepted_dt_s, maximum_cfl_number, initial_storage_m3, ...
            cumulative_inflow_m3, cumulative_outflow_m3, ...
            cumulative_adjustment_m3, stage_endpoint_clamp_count, ...
            maximum_stage_endpoint_excess_m);
        write_progress(input.progress_file, phase, time_s, duration_s, ...
            step_count, dt_s, partial_ledger, wall_elapsed_s);
        write_checkpoint(input.checkpoint_file, phase, time_s, duration_s, ...
            area, discharge, partial_ledger, wall_elapsed_s);
        last_diagnostic_wall_s = wall_elapsed_s;
    end
end

ledger = make_ledger(area, dx_m, step_count, minimum_accepted_dt_s, ...
    maximum_cfl_number, initial_storage_m3, cumulative_inflow_m3, ...
    cumulative_outflow_m3, cumulative_adjustment_m3, ...
    stage_endpoint_clamp_count, maximum_stage_endpoint_excess_m);
if input.boundary_formulation == "regime"
    ledger.boundary_steps = struct( ...
        'upstream_wall', upstream_code_counts(1), ...
        'upstream_supercritical_normal', upstream_code_counts(2), ...
        'upstream_subcritical_characteristic', upstream_code_counts(3), ...
        'upstream_two_condition_fallback', upstream_code_counts(4), ...
        'downstream_free_outflow', downstream_code_counts(1), ...
        'downstream_rating', downstream_code_counts(2), ...
        'downstream_critical_control', downstream_code_counts(3));
end
history = struct();
if record
    if ~isempty(overtopping) && history_time(history_count) ~= time_s
        % Keep the last accepted state of a stopped run in the history.
        history_count = history_count + 1;
        if history_count > history_capacity
            history_time(history_count, 1) = 0;
            history_area(history_count, :) = 0;
            history_discharge(history_count, :) = 0;
        end
        history_time(history_count) = time_s;
        history_area(history_count, :) = area.';
        history_discharge(history_count, :) = discharge.';
    end
    if ~outputs.face_flux
        maximum_face_flux = zeros(0, 1);
        probe_face_flux = zeros(probe_count, 0);
    end
    history = struct( ...
        'time_s', history_time(1:history_count), ...
        'area_m2', history_area(1:history_count, :), ...
        'discharge_m3s', history_discharge(1:history_count, :), ...
        'maxima', struct( ...
            'depth_m', maximum_depth, ...
            'stage_m', outputs.cells.invert_elevation_m + maximum_depth, ...
            'area_m2', maximum_area, ...
            'discharge_abs_m3s', maximum_discharge, ...
            'velocity_m_s', maximum_speed, ...
            'depth_velocity_m2_s', maximum_depth_speed, ...
            'time_of_maximum_depth_s', time_of_maximum_depth, ...
            'time_of_maximum_velocity_s', time_of_maximum_speed, ...
            'face_mass_flux_abs_m3s', maximum_face_flux), ...
        'probes', struct( ...
            'x_m', outputs.probe_x_m, ...
            'cell_index', probe_cells, ...
            'face_index', probe_faces, ...
            'time_s', probe_time(1:probe_count), ...
            'area_m2', probe_area(1:probe_count, :), ...
            'discharge_m3s', probe_discharge(1:probe_count, :), ...
            'depth_m', probe_depth(1:probe_count, :), ...
            'face_mass_flux_m3s', probe_face_flux(1:probe_count, :)));
end
end

function record = overtopping_record(phase, time_s, step_count, exception)
% A water level beyond a section table: the section is not wide enough for
% this flow, which is an applicability failure of the geometry, not of the
% solver. The run stops at the last accepted state.
location = regexp(exception.message, 'x = ([-+0-9.eE]+) m', 'tokens', 'once');
x_m = NaN;
if ~isempty(location)
    x_m = str2double(location{1});
end
record = struct('phase', phase, ...
    'model_time_s', time_s, ...
    'accepted_step_count', step_count, ...
    'x_m', x_m, ...
    'identifier', string(exception.identifier), ...
    'message', string(exception.message));
end

function speed = cell_speed(area, discharge, minimum_area)
speed = zeros(size(area));
wet = area > minimum_area;
speed(wet) = abs(discharge(wet)) ./ area(wet);
end

function outputs = output_plan(input, geometry, cell_x_m, face_x_m)
probe_x_m = input.probe_x_m(:);
probe_cells = zeros(numel(probe_x_m), 1);
probe_faces = zeros(numel(probe_x_m), 1);
for index = 1:numel(probe_x_m)
    [~, probe_cells(index)] = min(abs(cell_x_m - probe_x_m(index)));
    [~, probe_faces(index)] = min(abs(face_x_m - probe_x_m(index)));
end
outputs = struct('record', true, ...
    'interval_s', input.output_interval_s, ...
    'cells', geometry.cells, ...
    'probe_x_m', probe_x_m, ...
    'probe_cells', probe_cells, ...
    'probe_faces', probe_faces, ...
    'face_flux', input.kernel == "compiled");
end

function ledger = make_ledger(area, dx_m, step_count, ...
        minimum_accepted_dt_s, maximum_cfl_number, initial_storage_m3, ...
        cumulative_inflow_m3, cumulative_outflow_m3, ...
        cumulative_adjustment_m3, stage_endpoint_clamp_count, ...
        maximum_stage_endpoint_excess_m)
final_storage_m3 = sum(area) * dx_m;
residual_m3 = final_storage_m3 - initial_storage_m3 - ...
    (cumulative_inflow_m3 - cumulative_outflow_m3 + cumulative_adjustment_m3);
ledger = struct( ...
    'step_count', step_count, ...
    'minimum_accepted_dt_s', minimum_accepted_dt_s, ...
    'maximum_cfl_number', maximum_cfl_number, ...
    'initial_storage_m3', initial_storage_m3, ...
    'cumulative_inflow_m3', cumulative_inflow_m3, ...
    'cumulative_outflow_m3', cumulative_outflow_m3, ...
    'wet_dry_adjustment_m3', cumulative_adjustment_m3, ...
    'stage_endpoint_clamp_count', stage_endpoint_clamp_count, ...
    'maximum_stage_endpoint_excess_m', maximum_stage_endpoint_excess_m, ...
    'final_storage_m3', final_storage_m3, ...
    'residual_m3', residual_m3, ...
    'relative_residual', residual_m3 / max( ...
        initial_storage_m3 + abs(cumulative_inflow_m3), eps));
end

function write_progress(file_name, phase, time_s, duration_s, step_count, ...
        dt_s, ledger, wall_elapsed_s)
if strlength(file_name) == 0
    return
end
file_id = fopen(file_name, 'a');
if file_id < 0
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not append progress file %s.', file_name);
end
cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, ['%s\t%.12g\t%.12g\t%.12g\t%d\t%.12g\t%.12g\t' ...
    '%.12g\t%.12g\t%.12g\t%.12g\t%.6f\n'], ...
    phase, time_s, duration_s, time_s / duration_s, step_count, dt_s, ...
    ledger.maximum_cfl_number, ledger.final_storage_m3, ...
    ledger.cumulative_inflow_m3, ledger.cumulative_outflow_m3, ...
    ledger.wet_dry_adjustment_m3, wall_elapsed_s);
end

function write_checkpoint(file_name, phase, time_s, duration_s, area, ...
        discharge, ledger, wall_elapsed_s)
if strlength(file_name) == 0
    return
end
checkpoint = struct( ...
    'phase', phase, ...
    'model_time_s', time_s, ...
    'duration_s', duration_s, ...
    'progress_fraction', time_s / duration_s, ...
    'wall_elapsed_s', wall_elapsed_s, ...
    'area_m2', area, ...
    'discharge_m3s', discharge, ...
    'ledger', ledger);
temporary_file = string(tempname(fileparts(file_name))) + ".mat";
save(temporary_file, 'checkpoint', '-v7.3');
[moved, message] = movefile(temporary_file, file_name, 'f');
if ~moved
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not publish checkpoint %s: %s', file_name, message);
end
end

function step = make_step_function(cell_sections, face_sections, geometry, input)
% Both kernels take identical options; "reference" keeps the scalar H5b
% kernel available for equivalence checks.
options = {'gravity_m_s2', input.gravity_m_s2, ...
    'cfl_target', input.cfl_target, ...
    'minimum_area_m2', input.minimum_area_m2, ...
    'include_friction', input.include_friction};
if input.kernel == "compiled"
    if input.reconstruction ~= "stage"
        options = [options, {'reconstruction', input.reconstruction}];
    end
    if input.boundary_formulation ~= "legacy"
        options = [options, {'boundary_formulation', input.boundary_formulation}];
    end
    if strlength(input.negative_area_capture_file) > 0
        options = [options, {'report_negative_area', true, ...
            'negative_area_tolerance_m2', input.negative_area_tolerance_m2}];
    end
    options = [options, {'return_face_mass_flux', true}];
    step = @(area, discharge, dx_m, dt_s, boundary) ...
        hydrohp_varying_step_compiled(geometry, area, discharge, dx_m, ...
        dt_s, options{:}, 'boundary', boundary);
else
    step = @(area, discharge, dx_m, dt_s, boundary) ...
        hydrohp_varying_step(cell_sections, face_sections, area, ...
        discharge, dx_m, dt_s, options{:}, 'boundary', boundary);
end
end

function capture_negative_area(input, phase, time_s, dt_s, step_index, ...
        boundary, area, discharge, area_new, discharge_new, dx_m, ...
        initial_storage_m3, cumulative_inflow_m3, cumulative_outflow_m3, ...
        cumulative_adjustment_m3, diagnostic)
% Save the complete pre-step state of the first step whose raw area falls
% below -tolerance, then stop. Re-running hydrohp_varying_step_compiled
% from state_before with dt_s and boundary reproduces the event.
event = diagnostic.negative_area_event;
capture = struct( ...
    'phase', phase, ...
    'model_time_s', time_s, ...
    'dt_s', dt_s, ...
    'step_index', step_index, ...
    'boundary', boundary, ...
    'state_before', struct('area_m2', area, 'discharge_m3s', discharge), ...
    'state_after_clipping', struct('area_m2', area_new, ...
        'discharge_m3s', discharge_new), ...
    'dx_m', dx_m, ...
    'solver_options', struct('gravity_m_s2', input.gravity_m_s2, ...
        'cfl_target', input.cfl_target, ...
        'minimum_area_m2', input.minimum_area_m2, ...
        'include_friction', input.include_friction, ...
        'negative_area_tolerance_m2', input.negative_area_tolerance_m2), ...
    'ledger_before_step', struct('initial_storage_m3', initial_storage_m3, ...
        'storage_m3', sum(area) * dx_m, ...
        'cumulative_inflow_m3', cumulative_inflow_m3, ...
        'cumulative_outflow_m3', cumulative_outflow_m3, ...
        'wet_dry_adjustment_m3', cumulative_adjustment_m3), ...
    'step_ledger', struct( ...
        'boundary_inflow_volume_m3', diagnostic.boundary_inflow_volume_m3, ...
        'boundary_outflow_volume_m3', diagnostic.boundary_outflow_volume_m3, ...
        'wet_dry_adjustment_m3', diagnostic.volume_adjustment_m3, ...
        'storage_after_raw_m3', event.storage_after_raw_m3, ...
        'storage_after_clipping_m3', sum(area_new) * dx_m), ...
    'event', event);
file_name = input.negative_area_capture_file;
temporary_file = string(tempname(fileparts(file_name))) + ".mat";
save(temporary_file, 'capture', '-v7.3');
[moved, message] = movefile(temporary_file, file_name, 'f');
if ~moved
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not publish negative-area capture %s: %s', file_name, message);
end
first = event.records(1);
error('hydrohp:NegativeRawAreaCaptured', ...
    ['First raw area below -%.3g m2 in %s at t = %.9g s (step %d, ' ...
    'dt = %.6g s): cell %d at x = %.6g m has area_raw = %.6g m2; ' ...
    '%d cells negative. Capture saved to %s.'], ...
    input.negative_area_tolerance_m2, phase, time_s, step_index, dt_s, ...
    first.cell_index, first.x_m, first.area_raw_m2, ...
    event.negative_cell_count, file_name);
end

function boundary = make_boundary( ...
        downstream, upstream_discharge, initialization_type)
boundary = struct('upstream_discharge_m3s', upstream_discharge, ...
    'upstream_state_type', upstream_state_type(initialization_type), ...
    'downstream_type', lower(string(downstream.type)));
if boundary.downstream_type == "normal_depth"
    boundary.downstream_slope = downstream.slope;
elseif boundary.downstream_type == "stage"
    boundary.downstream_stage_m = downstream.stage_m;
end
end

function state_type = upstream_state_type(initialization_type)
if lower(string(initialization_type)) == "normal_depth"
    state_type = "local_depth";
else
    state_type = "stage";
end
end
