function result = hydrohp_run_varying(input)
%HYDROHP_RUN_VARYING Run the tested varying-section finite-volume kernel.

required = {'section_data', 'face_x_m', 'hydrograph_time_s', ...
    'hydrograph_discharge_m3s', 'duration_s', 'downstream'};
if ~isstruct(input) || ~isscalar(input) || ~all(isfield(input, required))
    error('hydrohp:InvalidVaryingInput', ...
        'Input must define sections, grid, hydrograph, duration, and downstream boundary.');
end
input = apply_defaults(input);
validate_input(input);
initialize_diagnostics(input);

face_x_m = input.face_x_m(:);
dx_m = diff(face_x_m);
if max(abs(dx_m - dx_m(1))) > 1e-10 * max(1, dx_m(1))
    error('hydrohp:NonuniformGrid', 'The H6 runner currently requires a uniform grid.');
end
dx_m = dx_m(1);
cell_x_m = face_x_m(1:end-1) + dx_m / 2;
cell_sections = hydrohp_map_sections_to_grid(input.section_data, cell_x_m);
face_sections = hydrohp_map_sections_to_grid(input.section_data, face_x_m);

[area_m2, discharge_m3s] = initial_state( ...
    cell_sections, face_sections, input);
initialization = struct('type', input.initialization_type, ...
    'base_discharge_m3s', input.base_discharge_m3s, ...
    'spinup_duration_s', input.spinup_duration_s, ...
    'converged', true, 'relative_discharge_error', 0, ...
    'relative_state_change_rate_per_s', 0, 'ledger', struct(), ...
    'final_area_m2', area_m2, 'final_discharge_m3s', discharge_m3s);

if input.spinup_duration_s > 0
    [area_m2, discharge_m3s, ~, initialization.ledger, ...
        initialization.relative_state_change_rate_per_s] = integrate( ...
        area_m2, discharge_m3s, input.spinup_duration_s, ...
        @(time) input.base_discharge_m3s, false, cell_sections, ...
        face_sections, dx_m, input, "spinup");
    initialization.relative_discharge_error = max(abs( ...
        discharge_m3s - input.base_discharge_m3s)) / ...
        max(1, abs(input.base_discharge_m3s));
    initialization.final_area_m2 = area_m2;
    initialization.final_discharge_m3s = discharge_m3s;
    initialization.converged = ...
        initialization.relative_state_change_rate_per_s <= ...
        input.steady_tolerance_per_s;
    if ~initialization.converged
        error('hydrohp:SteadyInitializationFailed', ...
            'Spin-up state still changes at %.6g per second.', ...
            initialization.relative_state_change_rate_per_s);
    end
end

forcing = @(time) interp1(input.hydrograph_time_s, ...
    input.hydrograph_discharge_m3s, time, 'linear');
[area_m2, discharge_m3s, history, ledger] = integrate( ...
    area_m2, discharge_m3s, input.duration_s, forcing, true, ...
    cell_sections, face_sections, dx_m, input, "event");

result = struct( ...
    'time_s', history.time_s, ...
    'x_m', cell_x_m, ...
    'area_m2', history.area_m2, ...
    'discharge_m3s', history.discharge_m3s, ...
    'final_area_m2', area_m2, ...
    'final_discharge_m3s', discharge_m3s, ...
    'ledger', ledger, ...
    'initialization', initialization, ...
    'metadata', struct('solver', "varying-section-hll", ...
        'cfl_target', input.cfl_target, ...
        'minimum_dt_s', input.minimum_dt_s, ...
        'maximum_dt_s', input.maximum_dt_s, ...
        'downstream', input.downstream, ...
        'include_friction', input.include_friction));
end

function input = apply_defaults(input)
defaults = struct( ...
    'gravity_m_s2', 9.81, ...
    'cfl_target', 0.7, ...
    'minimum_area_m2', 1e-10, ...
    'minimum_dt_s', 1e-5, ...
    'maximum_dt_s', 1, ...
    'include_friction', true, ...
    'base_discharge_m3s', input.hydrograph_discharge_m3s(1), ...
    'initialization_type', "normal_depth", ...
    'initial_stage_m', NaN, ...
    'spinup_duration_s', 0, ...
    'steady_tolerance_per_s', 1e-4, ...
    'progress_file', "", ...
    'checkpoint_file', "", ...
    'diagnostic_wall_interval_s', 300);
names = fieldnames(defaults);
for index = 1:numel(names)
    if ~isfield(input, names{index})
        input.(names{index}) = defaults.(names{index});
    end
end
input.progress_file = string(input.progress_file);
input.checkpoint_file = string(input.checkpoint_file);
end

function validate_input(input)
time = input.hydrograph_time_s(:);
discharge = input.hydrograph_discharge_m3s(:);
if numel(time) ~= numel(discharge) || numel(time) < 2 || ...
        any(~isfinite([time; discharge])) || any(diff(time) <= 0) || ...
        time(1) ~= 0 || input.duration_s <= 0 || time(end) < input.duration_s
    error('hydrohp:InvalidHydrograph', ...
        'Hydrograph arrays must be finite, increasing, start at zero, and cover duration_s.');
end
if any(discharge < 0)
    error('hydrohp:InvalidHydrograph', 'Negative upstream discharge is not supported.');
end
if ~isnumeric(input.face_x_m) || numel(input.face_x_m) < 3 || ...
        any(~isfinite(input.face_x_m)) || any(diff(input.face_x_m) <= 0)
    error('hydrohp:InvalidGrid', 'face_x_m must be finite and strictly increasing.');
end
positive_scalars = {'duration_s', 'gravity_m_s2', 'cfl_target', ...
    'minimum_dt_s', 'maximum_dt_s', 'steady_tolerance_per_s', ...
    'diagnostic_wall_interval_s'};
for index = 1:numel(positive_scalars)
    value = input.(positive_scalars{index});
    if ~isscalar(value) || ~isfinite(value) || value <= 0
        error('hydrohp:InvalidVaryingInput', ...
            '%s must be a positive finite scalar.', positive_scalars{index});
    end
end
if input.cfl_target > 1 || input.minimum_dt_s > input.maximum_dt_s || ...
        input.spinup_duration_s < 0 || input.minimum_area_m2 < 0
    error('hydrohp:InvalidVaryingInput', 'CFL, time-step, spin-up, or area limits are invalid.');
end
downstream_type = lower(string(input.downstream.type));
if ~isscalar(downstream_type) || ...
        ~ismember(downstream_type, ["normal_depth", "stage"])
    error('hydrohp:InvalidDownstreamType', ...
        'Downstream type must be "normal_depth" or "stage".');
end
if downstream_type == "normal_depth" && ...
        (~isfield(input.downstream, 'slope') || ...
        ~isscalar(input.downstream.slope) || ...
        ~isfinite(input.downstream.slope) || input.downstream.slope <= 0)
    error('hydrohp:InvalidDownstreamSlope', ...
        'A normal-depth boundary requires a positive finite slope.');
elseif downstream_type == "stage" && ...
        (~isfield(input.downstream, 'stage_m') || ...
        ~isscalar(input.downstream.stage_m) || ~isfinite(input.downstream.stage_m))
    error('hydrohp:InvalidDownstreamStage', ...
        'A stage boundary requires one finite stage_m value.');
end
for field_name = ["progress_file", "checkpoint_file"]
    value = input.(field_name);
    if ~isscalar(value) || (strlength(value) > 0 && ~isfolder(fileparts(value)))
        error('hydrohp:InvalidDiagnosticPath', ...
            '%s must be empty or name a file in an existing directory.', field_name);
    end
end
end

function initialize_diagnostics(input)
if strlength(input.progress_file) == 0
    return
end
file_id = fopen(input.progress_file, 'w');
if file_id < 0
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not create progress file %s.', input.progress_file);
end
cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, ['phase\tmodel_time_s\tduration_s\tprogress_fraction\t' ...
    'step_count\taccepted_dt_s\tmaximum_cfl_number\tstorage_m3\t' ...
    'cumulative_inflow_m3\tcumulative_outflow_m3\t' ...
    'wet_dry_adjustment_m3\twall_elapsed_s\n']);
end

function [area, discharge] = initial_state(sections, face_sections, input)
cell_count = numel(sections);
discharge = input.base_discharge_m3s * ones(cell_count, 1);
initialization_type = lower(string(input.initialization_type));
if initialization_type == "normal_depth"
    if lower(string(input.downstream.type)) ~= "normal_depth" || ...
            ~isfield(input.downstream, 'slope') || input.downstream.slope <= 0
        error('hydrohp:InvalidInitialization', ...
            'Normal-depth initialization requires a positive downstream slope.');
    end
    local_slope = ([face_sections(1:end-1).invert_elevation_m].' - ...
        [face_sections(2:end).invert_elevation_m].') ./ diff(input.face_x_m(:));
    if any(local_slope <= 0)
        error('hydrohp:InvalidInitialization', ...
            'Normal-depth initialization requires a positive local bed slope in every cell.');
    end
    target_conveyance = input.base_discharge_m3s ./ sqrt(local_slope);
    area = zeros(cell_count, 1);
    for index = 1:cell_count
        table_data = sections(index).table;
        if target_conveyance(index) > table_data.conveyance_m3s(end)
            error('hydrohp:InitializationOutsideSectionRange', ...
                'Base flow exceeds the conveyance range at x = %.6g m.', sections(index).x_m);
        end
        area(index) = interp1(table_data.conveyance_m3s, ...
            table_data.area_m2, target_conveyance(index), 'pchip');
    end
elseif initialization_type == "stage"
    stage = input.initial_stage_m;
    if isscalar(stage)
        stage = repmat(stage, cell_count, 1);
    end
    if ~isnumeric(stage) || numel(stage) ~= cell_count || any(~isfinite(stage))
        error('hydrohp:InvalidInitialization', ...
            'initial_stage_m must be a finite scalar or one value per cell.');
    end
    area = zeros(cell_count, 1);
    for index = 1:cell_count
        if stage(index) > sections(index).maximum_water_surface_elevation_m
            error('hydrohp:InitializationOutsideSectionRange', ...
                'Initial stage exceeds the section range at x = %.6g m.', ...
                sections(index).x_m);
        elseif stage(index) > sections(index).invert_elevation_m
            area(index) = interp1( ...
                sections(index).table.water_surface_elevation_m, ...
                sections(index).table.area_m2, stage(index), 'pchip');
        end
    end
else
    error('hydrohp:InvalidInitialization', ...
        'initialization_type must be "normal_depth" or "stage".');
end
end

function [area, discharge, history, ledger, final_change_rate_per_s] = integrate( ...
        area, discharge, duration_s, forcing, store_history, ...
        cell_sections, face_sections, dx_m, input, phase)
time_s = 0;
wall_timer = tic;
last_diagnostic_wall_s = -inf;
candidate_dt_s = input.maximum_dt_s;
initial_storage_m3 = sum(area) * dx_m;
cumulative_inflow_m3 = 0;
cumulative_outflow_m3 = 0;
cumulative_adjustment_m3 = 0;
final_change_rate_per_s = inf;
step_count = 0;
minimum_accepted_dt_s = inf;
maximum_cfl_number = 0;
stage_endpoint_clamp_count = 0;
maximum_stage_endpoint_excess_m = 0;
if store_history
    history = struct('time_s', 0, 'area_m2', area.', ...
        'discharge_m3s', discharge.');
else
    history = struct();
end

while time_s < duration_s
    dt_s = min(candidate_dt_s, duration_s - time_s);
    next_break = input.hydrograph_time_s(find( ...
        input.hydrograph_time_s > time_s, 1, 'first'));
    if ~isempty(next_break)
        dt_s = min(dt_s, next_break - time_s);
    end
    accepted = false;
    while ~accepted
        boundary = make_boundary(input.downstream, ...
            forcing(time_s + dt_s / 2), input.initialization_type);
        try
            [area_new, discharge_new, diagnostic] = hydrohp_varying_step( ...
                cell_sections, face_sections, area, discharge, dx_m, dt_s, ...
                gravity_m_s2=input.gravity_m_s2, cfl_target=input.cfl_target, ...
                minimum_area_m2=input.minimum_area_m2, ...
                include_friction=input.include_friction, boundary=boundary);
            accepted = true;
        catch exception
            if ~strcmp(exception.identifier, 'hydrohp:CFLViolation')
                rethrow(exception)
            end
            dt_s = dt_s / 2;
            if dt_s < input.minimum_dt_s
                error('hydrohp:MinimumTimeStep', ...
                    ['CFL control requires dt below minimum_dt_s at t = %.6g s. ' ...
                    'First-cell area/discharge are %.6g m2 and %.6g m3/s. ' ...
                    'Last diagnostic: %s'], time_s, area(1), discharge(1), ...
                    exception.message);
            end
        end
    end

    time_s = time_s + dt_s;
    step_count = step_count + 1;
    minimum_accepted_dt_s = min(minimum_accepted_dt_s, dt_s);
    maximum_cfl_number = max(maximum_cfl_number, diagnostic.cfl_number);
    area_change_rate = max(abs(area_new - area) ./ max(abs(area), 1e-6)) / dt_s;
    discharge_change_rate = max(abs(discharge_new - discharge)) / ...
        max(1, max(abs(discharge))) / dt_s;
    final_change_rate_per_s = max(area_change_rate, discharge_change_rate);
    area = area_new;
    discharge = discharge_new;
    cumulative_inflow_m3 = cumulative_inflow_m3 + ...
        diagnostic.boundary_inflow_volume_m3;
    cumulative_outflow_m3 = cumulative_outflow_m3 + ...
        diagnostic.boundary_outflow_volume_m3;
    cumulative_adjustment_m3 = cumulative_adjustment_m3 + ...
        diagnostic.volume_adjustment_m3;
    stage_endpoint_clamp_count = stage_endpoint_clamp_count + ...
        diagnostic.stage_endpoint_clamp_count;
    maximum_stage_endpoint_excess_m = max( ...
        maximum_stage_endpoint_excess_m, ...
        diagnostic.maximum_stage_endpoint_excess_m);
    candidate_dt_s = min(input.maximum_dt_s, 0.95 * diagnostic.recommended_dt_s);
    if candidate_dt_s < input.minimum_dt_s
        error('hydrohp:MinimumTimeStep', ...
            'The recommended step fell below minimum_dt_s at t = %.6g s.', time_s);
    end
    if store_history
        history.time_s(end + 1, 1) = time_s;
        history.area_m2(end + 1, :) = area.';
        history.discharge_m3s(end + 1, :) = discharge.';
    end
    wall_elapsed_s = toc(wall_timer);
    if wall_elapsed_s - last_diagnostic_wall_s >= ...
            input.diagnostic_wall_interval_s || time_s >= duration_s
        partial_ledger = make_ledger(area, dx_m, step_count, ...
            minimum_accepted_dt_s, maximum_cfl_number, initial_storage_m3, ...
            cumulative_inflow_m3, cumulative_outflow_m3, ...
            cumulative_adjustment_m3, stage_endpoint_clamp_count, ...
            maximum_stage_endpoint_excess_m);
        write_progress(input.progress_file, phase, time_s, duration_s, ...
            step_count, dt_s, partial_ledger, wall_elapsed_s);
        write_checkpoint(input.checkpoint_file, phase, time_s, duration_s, ...
            area, discharge, partial_ledger, wall_elapsed_s);
        last_diagnostic_wall_s = wall_elapsed_s;
    end
end

ledger = make_ledger(area, dx_m, step_count, minimum_accepted_dt_s, ...
    maximum_cfl_number, initial_storage_m3, cumulative_inflow_m3, ...
    cumulative_outflow_m3, cumulative_adjustment_m3, ...
    stage_endpoint_clamp_count, maximum_stage_endpoint_excess_m);
end

function ledger = make_ledger(area, dx_m, step_count, ...
        minimum_accepted_dt_s, maximum_cfl_number, initial_storage_m3, ...
        cumulative_inflow_m3, cumulative_outflow_m3, ...
        cumulative_adjustment_m3, stage_endpoint_clamp_count, ...
        maximum_stage_endpoint_excess_m)
final_storage_m3 = sum(area) * dx_m;
residual_m3 = final_storage_m3 - initial_storage_m3 - ...
    (cumulative_inflow_m3 - cumulative_outflow_m3 + cumulative_adjustment_m3);
ledger = struct( ...
    'step_count', step_count, ...
    'minimum_accepted_dt_s', minimum_accepted_dt_s, ...
    'maximum_cfl_number', maximum_cfl_number, ...
    'initial_storage_m3', initial_storage_m3, ...
    'cumulative_inflow_m3', cumulative_inflow_m3, ...
    'cumulative_outflow_m3', cumulative_outflow_m3, ...
    'wet_dry_adjustment_m3', cumulative_adjustment_m3, ...
    'stage_endpoint_clamp_count', stage_endpoint_clamp_count, ...
    'maximum_stage_endpoint_excess_m', maximum_stage_endpoint_excess_m, ...
    'final_storage_m3', final_storage_m3, ...
    'residual_m3', residual_m3, ...
    'relative_residual', residual_m3 / max( ...
        initial_storage_m3 + abs(cumulative_inflow_m3), eps));
end

function write_progress(file_name, phase, time_s, duration_s, step_count, ...
        dt_s, ledger, wall_elapsed_s)
if strlength(file_name) == 0
    return
end
file_id = fopen(file_name, 'a');
if file_id < 0
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not append progress file %s.', file_name);
end
cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, ['%s\t%.12g\t%.12g\t%.12g\t%d\t%.12g\t%.12g\t' ...
    '%.12g\t%.12g\t%.12g\t%.12g\t%.6f\n'], ...
    phase, time_s, duration_s, time_s / duration_s, step_count, dt_s, ...
    ledger.maximum_cfl_number, ledger.final_storage_m3, ...
    ledger.cumulative_inflow_m3, ledger.cumulative_outflow_m3, ...
    ledger.wet_dry_adjustment_m3, wall_elapsed_s);
end

function write_checkpoint(file_name, phase, time_s, duration_s, area, ...
        discharge, ledger, wall_elapsed_s)
if strlength(file_name) == 0
    return
end
checkpoint = struct( ...
    'phase', phase, ...
    'model_time_s', time_s, ...
    'duration_s', duration_s, ...
    'progress_fraction', time_s / duration_s, ...
    'wall_elapsed_s', wall_elapsed_s, ...
    'area_m2', area, ...
    'discharge_m3s', discharge, ...
    'ledger', ledger);
temporary_file = string(tempname(fileparts(file_name))) + ".mat";
save(temporary_file, 'checkpoint', '-v7.3');
[moved, message] = movefile(temporary_file, file_name, 'f');
if ~moved
    error('hydrohp:DiagnosticWriteFailed', ...
        'Could not publish checkpoint %s: %s', file_name, message);
end
end

function boundary = make_boundary( ...
        downstream, upstream_discharge, initialization_type)
boundary = struct('upstream_discharge_m3s', upstream_discharge, ...
    'upstream_state_type', upstream_state_type(initialization_type), ...
    'downstream_type', lower(string(downstream.type)));
if boundary.downstream_type == "normal_depth"
    boundary.downstream_slope = downstream.slope;
elseif boundary.downstream_type == "stage"
    boundary.downstream_stage_m = downstream.stage_m;
end
end

function state_type = upstream_state_type(initialization_type)
if lower(string(initialization_type)) == "normal_depth"
    state_type = "local_depth";
else
    state_type = "stage";
end
end
