function metrics = test_dry_start
%TEST_DRY_START A reach that starts dry, as in the 2D benchmark, is wetted
% by the hydrograph alone: zero initial storage, the exact hydrograph volume
% enters, volume is conserved, and no spin-up is needed.

repository_root = fileparts(fileparts(mfilename('fullpath')));
addpath(repository_root);
time_s = [0; 60; 300; 600; 1800];
discharge_m3s = [0; 30; 10; 0; 0];
input = struct( ...
    'section_data', channel([1; 0.5; 0]), ...
    'face_x_m', linspace(0, 600, 41).', ...
    'hydrograph_time_s', time_s, ...
    'hydrograph_discharge_m3s', discharge_m3s, ...
    'duration_s', 1800, ...
    'downstream', struct('type', "normal_depth", 'slope', 1/600), ...
    'base_discharge_m3s', 0, ...
    'initialization_type', "dry", ...
    'spinup_duration_s', 0, ...
    'maximum_dt_s', 2, ...
    'output_interval_s', 60);
result = hydrohp_run_varying(input);
ledger = result.ledger;
assert(result.status == "completed");
assert(ledger.initial_storage_m3 == 0);
assert(abs(ledger.cumulative_inflow_m3 - trapz(time_s, discharge_m3s)) < 1e-9 * ...
    trapz(time_s, discharge_m3s));
assert(abs(ledger.relative_residual) < 1e-12);
assert(abs(ledger.wet_dry_adjustment_m3) < 1e-6);
assert(ledger.cumulative_outflow_m3 > 0);
assert(ledger.boundary_steps.upstream_wall > 0);
assert(max(result.maxima.depth_m) > 0);
assert(result.metadata.boundary_formulation == "regime");

metrics = struct('inflow_m3', ledger.cumulative_inflow_m3, ...
    'outflow_m3', ledger.cumulative_outflow_m3, ...
    'final_storage_m3', ledger.final_storage_m3);
fprintf('HydroHP dry-start checks passed: inflow %.1f m3, outflow %.1f m3.\n', ...
    metrics.inflow_m3, metrics.outflow_m3);
end

function sections = channel(invert_m)
chainage_m = [0; 300; 600];
rows = table();
for index = 1:numel(chainage_m)
    section = table( ...
        repmat("S" + index, 4, 1), repmat(chainage_m(index), 4, 1), ...
        [0; 4; 12; 16], invert_m(index) + [4; 0; 0; 4], ...
        0.035 * ones(4, 1), ...
        'VariableNames', {'section_id', 'chainage_m', 'offset_m', ...
        'elevation_m', 'manning_n'});
    rows = [rows; section]; %#ok<AGROW>
end
sections = hydrohp_build_section_tables(rows, 0.02, "scm");
end
