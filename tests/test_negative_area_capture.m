function metrics = test_negative_area_capture
%TEST_NEGATIVE_AREA_CAPTURE P0.1: capture the first negative raw area.
%
% A steep channel whose normal depth is smaller than half the bed drop per
% cell reproduces the H8 Bonitinho mechanism: stage-based reconstruction on
% the lower downstream face gives the upstream state more depth than its
% cell holds, so one CFL-limited step drains more volume than is available.
% The capture must be deterministic and must not change the solver result.

repository_root = fileparts(fileparts(mfilename('fullpath')));
addpath(repository_root);
capture_root = string(tempname);
mkdir(capture_root);
cleanup = onCleanup(@() rmdir(capture_root, 's'));

input = struct( ...
    'section_data', channel_sections([8; 8; 40], 0.03), ...
    'face_x_m', linspace(0, 600, 21).', ...
    'hydrograph_time_s', [0; 600], ...
    'hydrograph_discharge_m3s', [2; 2], ...
    'duration_s', 60, ...
    'downstream', struct('type', "normal_depth", 'slope', 0.002), ...
    'base_discharge_m3s', 2, ...
    'initialization_type', "normal_depth", ...
    'spinup_duration_s', 600, ...
    'steady_tolerance_per_s', 1e9, ...
    'maximum_dt_s', 5, ...
    'cfl_target', 0.7, ...
    'reconstruction', "stage", ...
    'negative_area_capture_file', fullfile(capture_root, "capture.mat"));

% The capture stops the run with a dedicated identifier.
identifier = "";
try
    hydrohp_run_varying(input);
catch exception
    identifier = string(exception.identifier);
end
assert(identifier == "hydrohp:NegativeRawAreaCaptured", ...
    'Expected a negative raw-area capture, got "%s".', identifier);
first = load(input.negative_area_capture_file).capture;
event = first.event;
record = event.records(1);
assert(first.phase == "spinup");
assert(event.negative_cell_count >= 1 && record.area_raw_m2 < 0);
assert(event.cfl_number <= input.cfl_target);

% Mechanism: below the CFL limit, the step drains more than the cell holds
% because the reconstructed upstream face depth exceeds the cell depth.
assert(record.local_cfl_right < 1);
assert(record.outgoing_to_available_ratio > 1);
assert(record.right_face.left_stage_m - record.right_face.invert_elevation_m > ...
    record.previous_depth_m);

% Determinism: a second run captures the same step and state.
input_repeat = input;
input_repeat.negative_area_capture_file = fullfile(capture_root, "repeat.mat");
try
    hydrohp_run_varying(input_repeat);
catch
end
second = load(input_repeat.negative_area_capture_file).capture;
assert(isequaln(first.event, second.event) && ...
    isequaln(first.state_before, second.state_before));

% Replaying the saved pre-step state reproduces the raw update, and the
% clipped state equals the normal solver update, so capture changes nothing.
[cells, faces] = grid_sections(input);
geometry = hydrohp_compile_geometry(cells, faces);
options = first.solver_options;
[area_new, discharge_new, diagnostic] = hydrohp_varying_step_compiled( ...
    geometry, first.state_before.area_m2, first.state_before.discharge_m3s, ...
    first.dx_m, first.dt_s, gravity_m_s2=options.gravity_m_s2, ...
    cfl_target=options.cfl_target, minimum_area_m2=options.minimum_area_m2, ...
    include_friction=options.include_friction, boundary=first.boundary, ...
    report_negative_area=true, ...
    negative_area_tolerance_m2=options.negative_area_tolerance_m2);
assert(isequaln(diagnostic.negative_area_event, event));
assert(isequal(area_new, first.state_after_clipping.area_m2));
assert(isequal(discharge_new, first.state_after_clipping.discharge_m3s));
[area_plain, discharge_plain] = hydrohp_varying_step( ...
    cells, faces, first.state_before.area_m2, ...
    first.state_before.discharge_m3s, first.dx_m, first.dt_s, ...
    gravity_m_s2=options.gravity_m_s2, cfl_target=options.cfl_target, ...
    minimum_area_m2=options.minimum_area_m2, ...
    include_friction=options.include_friction, boundary=first.boundary);
assert(isequal(area_plain, area_new) && isequal(discharge_plain, discharge_new));

% The capture needs the compiled kernel.
input.kernel = "reference";
try
    hydrohp_run_varying(input);
    error('hydrohp:TestFailed', 'Capture with the reference kernel was accepted.');
catch exception
    assert(strcmp(exception.identifier, 'hydrohp:InvalidVaryingInput'));
end

metrics = struct('first_cell_index', record.cell_index, ...
    'model_time_s', first.model_time_s, ...
    'step_index', first.step_index, ...
    'minimum_raw_area_m2', event.minimum_raw_area_m2, ...
    'outgoing_to_available_ratio', record.outgoing_to_available_ratio, ...
    'local_cfl_right', record.local_cfl_right);
fprintf(['HydroHP negative-area capture checks passed: cell %d, step %d, ' ...
    'outgoing/available %.3f at local CFL %.3f.\n'], record.cell_index, ...
    first.step_index, record.outgoing_to_available_ratio, ...
    record.local_cfl_right);
end

function [cells, faces] = grid_sections(input)
face_x_m = input.face_x_m;
dx_m = face_x_m(2) - face_x_m(1);
cells = hydrohp_map_sections_to_grid(input.section_data, ...
    face_x_m(1:end-1) + dx_m / 2);
faces = hydrohp_map_sections_to_grid(input.section_data, face_x_m);
end

function sections = channel_sections(bottom_width_m, slope)
chainage_m = [0; 300; 600];
rows = table();
for index = 1:numel(chainage_m)
    w = bottom_width_m(index);
    invert = 20 - slope * chainage_m(index);
    section = table( ...
        repmat("S" + index, 4, 1), repmat(chainage_m(index), 4, 1), ...
        [0; 2; 2 + w; 4 + w], invert + [4; 0; 0; 4], ...
        0.035 * ones(4, 1), ...
        'VariableNames', {'section_id', 'chainage_m', 'offset_m', ...
        'elevation_m', 'manning_n'});
    rows = [rows; section]; %#ok<AGROW>
end
sections = hydrohp_build_section_tables(rows, 0.02, "scm");
end
